GROUP_SERVICE_PREFIXES: tuple[str, ...] = (
    "🎧",
    "⏹",
    "📊",
    "🔎",
    "🧠",
    "Привет! Я «Командный помощник»",
    "Как со мной работать",
    "Чтобы задать вопрос",
)


def is_service_text(text: str | None) -> bool:
    """Проверить, является ли текст служебным ответом бота.

    Такие сообщения нельзя сохранять в долговременную память и передавать
    в агента как данные пользователя.
    """
    normalized = (text or "").strip()
    if not normalized:
        # Пустой текст — тоже не данные для сохранения.
        return True
    if normalized in SERVICE_REPLIES:
        return True
    if normalized in GROUP_SERVICE_REPLIES:
        return True
    if normalized in set(TOOL_STATUS.values()):
        return True
    # Персонализированное приветствие («Привет, Иван! Я умный помощник…»)
    # тоже является служебным текстом бота.
    if "умный помощник на Haystack" in normalized:
        return True
    if "«Командный помощник»" in normalized:
        return True
    return normalized.startswith(SERVICE_PREFIXES + GROUP_SERVICE_PREFIXES)
